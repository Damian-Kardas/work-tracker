-- =========================================================
-- Avatar uzytkownika (zdjecie profilowe)
-- Uruchom w Supabase: SQL Editor -> New query -> wklej -> Run
-- =========================================================

alter table public.profiles
  add column if not exists avatar_url text;

-- Bucket na zdjecia profilowe (publiczny odczyt, zapis tylko wlasciciela)
insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', true)
on conflict (id) do nothing;

create policy "avatar_public_read" on storage.objects
  for select using (bucket_id = 'avatars');

create policy "avatar_owner_insert" on storage.objects
  for insert with check (
    bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text
  );

create policy "avatar_owner_update" on storage.objects
  for update using (
    bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text
  );

create policy "avatar_owner_delete" on storage.objects
  for delete using (
    bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text
  );
